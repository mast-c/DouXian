"""Repair stale nodes remaining after drug_db_v2_cleaned.json was imported.

Read-only by default. Uses exact hash IDs generated by the project's kg.build,
rather than guessing which graph nodes should be deleted based on name patterns.

Usage:
  python -m kg.repair_residuals --old-json PATH --clean-json PATH --manifest data/kg_output_clean_v2
  python -m kg.repair_residuals --old-json PATH --clean-json PATH --manifest data/kg_output_clean_v2 --apply --backup-confirmed
"""
import argparse
from collections import Counter
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path

from kg.build import entity_id, text_of, file_sha256

DATASET = "MedGraphRAG-Drug-DB drug_db_v2.json"
ALLOWED_INTERACTION_RELATIONS = [
    "SOURCE_MENTION", "TARGET_MENTION", "SOURCE_DRUG",
    "TARGET_DRUG", "SUPPORTED_BY",
]

def load_json(path):
    with Path(path).open("r", encoding="utf-8-sig") as f:
        data = json.load(f)
    if (not isinstance(data, dict)
            or not isinstance(data.get("drugs"), dict)
            or not isinstance(data.get("interactions"), list)):
        raise ValueError("Expected data with 'drugs' dictionary and 'interactions' list")
    return data

def iter_jsonl(path):
    with Path(path).open("r", encoding="utf-8") as f:
        for index, line in enumerate(f, 1):
            if line.strip():
                try:
                    yield json.loads(line)
                except json.JSONDecodeError as e:
                    raise ValueError(f"{path}:{index} not valid JSONL") from e

def expected_ids(data):
    drug_ids = {entity_id("Drug", name) for name in data["drugs"]}
    interaction_rows = {}
    mention_ids = set()
    invalid = 0
    for item in data["interactions"]:
        if not isinstance(item, dict):
            invalid += 1
            continue
        pair = item.get("pair")
        if (not isinstance(pair, (list, tuple)) or len(pair) != 2
                or not all(isinstance(n, str) and n.strip() for n in pair)):
            invalid += 1
            continue
        source, target = (x.strip() for x in pair)
        note = text_of(item.get("note"))
        interaction_id = entity_id("InteractionCandidate", source, target, note)
        if interaction_id in interaction_rows:
            # Same ID is the same fact in our previous import logic.
            continue
        interaction_rows[interaction_id] = {
            "id": interaction_id, "source_name": source,
            "target_name": target,
        }
        mention_ids.add(entity_id("Mention", source))
        mention_ids.add(entity_id("Mention", target))
    return {
        "drugs": drug_ids,
        "interactions": interaction_rows,
        "mentions": mention_ids,
        "invalid_interactions": invalid,
    }

def batch(items, size=350):
    items = list(items)
    for i in range(0, len(items), size):
        yield items[i:i+size]

def count_nodes(session, label, *, dataset=None):
    if dataset is None:
        query = f"MATCH (n:{label}) RETURN count(n) AS n"
        return session.run(query).single()["n"]
    return session.run(
        f"MATCH (n:{label}) WHERE n.dataset=$dataset RETURN count(n) AS n",
        dataset=dataset,
    ).single()["n"]

def count_present(session, label, ids):
    total = 0
    for piece in batch(sorted(ids), 400):
        n = session.run(f"""
            UNWIND $ids AS id
            OPTIONAL MATCH (node:{label} {{id:id}})
            RETURN count(node) AS n
        """, ids=piece).single()["n"]
        total += n
    return total

def inspect_stale_interactions(session, stale):
    present, missing, blocked = 0, 0, []
    for group in batch([stale[x] for x in sorted(stale)], 250):
        rows = session.run("""
          UNWIND $rows AS row
          OPTIONAL MATCH (c:InteractionCandidate {id:row.id})
          OPTIONAL MATCH (c)-[edge]-()
          WITH row, c, collect(DISTINCT type(edge)) AS relationship_types
          RETURN row.id AS id,
                 row.source_name AS expected_source,
                 row.target_name AS expected_target,
                 c.id AS actual_id,
                 c.source_name AS actual_source,
                 c.target_name AS actual_target,
                 c.clinical_status AS clinical_status,
                 relationship_types
        """, rows=group)
        for row in rows:
            data = dict(row)
            if data["actual_id"] is None:
                missing += 1
                continue
            present += 1
            external_relations = [
                x for x in data["relationship_types"]
                if x not in ALLOWED_INTERACTION_RELATIONS
            ]
            if (data["actual_source"] != data["expected_source"]
                    or data["actual_target"] != data["expected_target"]
                    or data["clinical_status"] != "not_validated"
                    or external_relations):
                blocked.append({
                    "id": data["id"],
                    "reason": "unexpected candidate properties or external relations",
                    "unexpected_relations": external_relations,
                })
    return present, missing, blocked

def inspect_old_drugs(session, stale_drug_ids):
    present = 0
    with_relations = Counter()
    isolated = 0
    samples = []
    for ids in batch(sorted(stale_drug_ids), 200):
        rows = session.run("""
          UNWIND $ids AS id
          OPTIONAL MATCH (d:Drug {id:id})
          OPTIONAL MATCH (d)-[r]-()
          WITH id, d, collect(DISTINCT type(r)) AS relationships
          RETURN d.id AS actual_id, d.name AS name, relationships
        """, ids=ids)
        for row in rows:
            if row["actual_id"] is None:
                continue
            present += 1
            if row["relationships"]:
                for label in row["relationships"]:
                    with_relations[label] += 1
                if len(samples) < 20:
                    samples.append({
                        "name": row["name"],
                        "relations": row["relationships"],
                    })
            else:
                isolated += 1
    return {
        "obsolete_drug_nodes_still_present": present,
        "already_isolated_and_removable": isolated,
        "remaining_link_types": dict(with_relations),
        "examples_with_links": samples,
    }

def tx_delete_stale_candidates(tx, rows):
    row = tx.run("""
      UNWIND $rows AS item
      MATCH (c:InteractionCandidate {id:item.id})
      WHERE c.clinical_status='not_validated'
        AND c.source_name=item.source_name
        AND c.target_name=item.target_name
        AND NOT EXISTS {
          MATCH (c)-[e]-()
          WHERE NOT (type(e) IN $allowed)
        }
      DETACH DELETE c
      RETURN count(*) AS deleted
    """, rows=rows, allowed=ALLOWED_INTERACTION_RELATIONS).single()
    return row["deleted"]

def tx_delete_orphan_drugs(tx, ids):
    result = tx.run("""
      UNWIND $ids AS id
      MATCH (d:Drug {id:id})
      WHERE NOT EXISTS { MATCH (d)--() }
      DELETE d
      RETURN count(*) AS deleted
    """, ids=ids).single()
    return result["deleted"]

def tx_delete_orphan_mentions(tx, ids):
    result = tx.run("""
      UNWIND $ids AS id
      MATCH (m:NameMention {id:id})
      WHERE m.semantic_status='unresolved_name_or_category'
        AND NOT EXISTS { MATCH (m)--() }
      DELETE m
      RETURN count(*) AS deleted
    """, ids=ids).single()
    return result["deleted"]

def repair(old_json, clean_json, manifest, *, apply=False,
           backup_confirmed=False, database="neo4j", uri=None, user=None,
           password=None):
    old_json, clean_json = Path(old_json), Path(clean_json)
    manifest = Path(manifest)
    old = expected_ids(load_json(old_json))
    new = expected_ids(load_json(clean_json))

    report_path = manifest / "build_report.json"
    if not report_path.is_file():
        raise FileNotFoundError("Missing build_report.json in clean manifest directory")
    build_report = json.loads(report_path.read_text(encoding="utf-8"))
    if build_report.get("sample_limit") != 0:
        raise RuntimeError("Clean manifest is partial. Require --limit 0 full export")
    if build_report.get("input_sha256") != file_sha256(clean_json):
        raise RuntimeError("Clean JSON hash differs from manifest. Rebuild before repair")

    manifest_candidates = {
        row["id"] for row in iter_jsonl(manifest / "interaction_candidates.jsonl")
    }
    manifest_drugs = {
        row["id"] for row in iter_jsonl(manifest / "drugs.jsonl")
    }
    manifest_sources = {
        row["id"] for row in iter_jsonl(manifest / "source_records.jsonl")
    }
    if len(manifest_sources) != build_report.get("counts", {}).get("source_records"):
        raise RuntimeError("Clean source record count disagrees with build report")
    if (manifest_candidates != set(new["interactions"])
            or manifest_drugs != new["drugs"]):
        raise RuntimeError(
            "Cleaned manifest IDs disagree with cleaned JSON. Do not delete anything"
        )

    stale_interactions = {
        key: old["interactions"][key]
        for key in (set(old["interactions"]) - set(new["interactions"]))
    }
    stale_drugs = old["drugs"] - new["drugs"]
    stale_mentions = old["mentions"] - new["mentions"]
    if not stale_interactions and not stale_drugs and not stale_mentions:
        raise RuntimeError("No differences detected. Verify that old JSON was not overwritten")

    try:
        from dotenv import load_dotenv
        load_dotenv(override=False)
    except ImportError:
        pass

    from neo4j import GraphDatabase
    uri = uri or os.getenv("NEO4J_URI", "bolt://localhost:7687")
    user = user or os.getenv("NEO4J_USER", "neo4j")
    password = password or os.getenv("NEO4J_PASSWORD")
    if not password:
        raise RuntimeError("Set NEO4J_PASSWORD in your .env or environment")

    driver = GraphDatabase.driver(uri, auth=(user, password))
    try:
        driver.verify_connectivity()
        with driver.session(database=database) as session:
            before = {
                "Drug": count_nodes(session, "Drug"),
                "SourceRecord_for_dataset": count_nodes(
                    session, "SourceRecord", dataset=DATASET
                ),
                "InteractionCandidate": count_nodes(session, "InteractionCandidate"),
            }
            present_drugs = count_present(session, "Drug", new["drugs"])
            present_sources = count_present(session, "SourceRecord", manifest_sources)
            present_candidates = count_present(
                session, "InteractionCandidate", new["interactions"]
            )
            stale_present, stale_missing, blockers = inspect_stale_interactions(
                session, stale_interactions
            )
            drug_report = inspect_old_drugs(session, stale_drugs)

            report = {
                "mode": "PREVIEW" if not apply else "APPLY_REQUESTED",
                "utc": datetime.now(timezone.utc).isoformat(),
                "database": database,
                "snapshot_sha256": file_sha256(clean_json),
                "current_nodes": before,
                "expected_clean": {
                    "Drug": len(new["drugs"]),
                    "SourceRecord": len(manifest_sources),
                    "InteractionCandidate": len(new["interactions"]),
                },
                "current_expected_nodes_present": {
                    "Drug": present_drugs,
                    "SourceRecord": present_sources,
                    "InteractionCandidate": present_candidates,
                },
                "obsolete_interaction_ids": len(stale_interactions),
                "obsolete_interactions_present_in_db": stale_present,
                "obsolete_interactions_missing_in_db": stale_missing,
                "obsolete_interactions_blocked": len(blockers),
                "blocked_samples": blockers[:10],
                "obsolete_drugs": drug_report,
                "obsolete_mention_ids": len(stale_mentions),
                "warning": (
                    "All deletes are scoped by exact old-vs-clean IDs. "
                    "This does not validate medical facts."
                ),
            }
            report_file = manifest / (
                "residual_repair_result.json" if apply
                else "residual_repair_preview.json"
            )
            # Always create a preview file, even when guards prevent mutation.
            report_file.write_text(
                json.dumps(report, ensure_ascii=False, indent=2),
                encoding="utf-8",
            )
            print(json.dumps(report, ensure_ascii=False, indent=2))

            if not apply:
                return report
            if not backup_confirmed:
                raise RuntimeError("No changes made: --backup-confirmed is required")
            if blockers:
                raise RuntimeError("No changes made: stale candidates have protected links")
            if (present_drugs != len(new["drugs"])
                    or present_sources != len(manifest_sources)
                    or present_candidates != len(new["interactions"])):
                raise RuntimeError(
                    "No changes made: current clean graph is incomplete. "
                    "Repair the sync import before deleting old nodes"
                )

            deleted_candidates = 0
            deleted_drugs = 0
            deleted_mentions = 0
            for rows in batch([stale_interactions[k] for k in sorted(stale_interactions)], 150):
                deleted_candidates += session.execute_write(
                    tx_delete_stale_candidates, rows
                )
            for ids in batch(sorted(stale_drugs), 150):
                deleted_drugs += session.execute_write(
                    tx_delete_orphan_drugs, ids
                )
            for ids in batch(sorted(stale_mentions), 150):
                deleted_mentions += session.execute_write(
                    tx_delete_orphan_mentions, ids
                )

            after = {
                "Drug": count_nodes(session, "Drug"),
                "SourceRecord_for_dataset": count_nodes(
                    session, "SourceRecord", dataset=DATASET
                ),
                "InteractionCandidate": count_nodes(session, "InteractionCandidate"),
            }
            # Count remaining exact obsolete nodes; do not rely on total count alone.
            remaining_stale, _, post_blockers = inspect_stale_interactions(
                session, stale_interactions
            )
            outcome = {
                "mode": "APPLIED",
                "deleted_candidates": deleted_candidates,
                "deleted_orphan_drugs": deleted_drugs,
                "deleted_orphan_mentions": deleted_mentions,
                "remaining_obsolete_candidates": remaining_stale,
                "remaining_blocked_candidates": len(post_blockers),
                "nodes_after": after,
                "expected_clean": report["expected_clean"],
                "note": (
                    "If Drug count remains above the clean expected count, "
                    "remaining old nodes have relationships; do not force-delete"
                ),
            }
            (manifest / "residual_repair_result.json").write_text(
                json.dumps(outcome, ensure_ascii=False, indent=2),
                encoding="utf-8",
            )
            print(json.dumps(outcome, ensure_ascii=False, indent=2))
            return outcome
    finally:
        driver.close()

def main():
    p = argparse.ArgumentParser(
        description="Safe residual cleanup for drug_db_v2 -> drug_db_v2_cleaned"
    )
    p.add_argument("--old-json", required=True)
    p.add_argument("--clean-json", required=True)
    p.add_argument("--manifest", default="data/kg_output_clean_v2")
    p.add_argument("--database", default=os.getenv("NEO4J_DATABASE", "neo4j"))
    p.add_argument("--uri")
    p.add_argument("--user")
    p.add_argument("--password")
    p.add_argument("--apply", action="store_true")
    p.add_argument("--backup-confirmed", action="store_true")
    a = p.parse_args()
    repair(a.old_json, a.clean_json, a.manifest, apply=a.apply,
           backup_confirmed=a.backup_confirmed, database=a.database,
           uri=a.uri, user=a.user, password=a.password)

if __name__ == "__main__":
    main()
